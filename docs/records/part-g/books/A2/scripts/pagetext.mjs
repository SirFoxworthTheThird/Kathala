import { open, sleep, W } from './lib.mjs';
const [tab, n] = process.argv.slice(2);
const { ctx, page } = await open();
await page.goto(W + '/manuscript');
await sleep(3000);
await page.getByRole('tab', { name: new RegExp('^' + tab) }).first().click();
